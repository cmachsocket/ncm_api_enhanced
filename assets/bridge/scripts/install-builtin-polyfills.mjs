#!/usr/bin/env node
// assets/bridge/scripts/install-builtin-polyfills.mjs
//
// One-shot installer. Reads bare-node-runtime/imports.json (the
// authoritative Node → bare-* redirect map) and synthesises a
// node_modules/<name>/ polyfill package for every specifier.
//
// Why this exists
// ---------------
//
// bare-pack's resolver does NOT auto-redirect require('fs') ->
// require('bare-fs') the way Node's loader does. bare-node-runtime
// ships an `imports.json` mapping every Node builtin to its bare-*
// counterpart, but that map is consumed by bare-pack's ESM
// `import x with {imports: 'X'}` path only — it has no effect on
// plain CJS `require()`.
//
// Pack.mjs feeds bridge.js into bare-pack and bridge.js + every
// upstream module uses CJS require. Without redirects, the resolver
// hits MODULE_NOT_FOUND the moment it walks into something like
// `require('readline')` (bridge.js) or `require('fs')` /
// `require('crypto')` (transitive deps).
//
// Workaround: drop a tiny shim package into node_modules/<name>/
// that re-exports the bare-* implementation. bare-pack's resolver
// looks for node_modules/<name>/ the same way it would for any
// normal package, finds the shim, and pulls in bare-* transparently.
//
// For sub-paths (e.g. 'fs/promises', 'path/posix'), the shim's main
// entry is ./<sub>.js inside node_modules/<name>/ so both
// `require('fs')` and `require('fs/promises')` resolve through the
// same package root.
//
// This must stay in sync with imports.json. Re-run after bumping
// bare-node-runtime:
//
//   node scripts/install-builtin-polyfills.mjs
//
// Idempotent — safe to re-run.

import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const bridgeDir = resolve(scriptDir, "..");
const importsPath = resolve(
  bridgeDir,
  "node_modules/bare-node-runtime/imports.json",
);
const nodeModulesDir = resolve(bridgeDir, "node_modules");

const map = JSON.parse(await readFile(importsPath, "utf8"));

//
// Group specifiers by their top-level package name so each
// node_modules/<name>/ has one package.json listing every sub-path.
//

const byPackage = new Map();

for (const [specifier, target] of Object.entries(map)) {
  // imports.json has duplicate "node:*" entries that share targets
  // with the bare names; the node_modules/<bare-name>/ shim covers
  // both since bare-pack only resolves the bare specifier.

  if (specifier.startsWith("node:")) continue;

  const bare = target?.bare;

  if (typeof bare !== "string") continue;

  const packageName = specifier.split("/")[0];

  if (!byPackage.has(packageName)) byPackage.set(packageName, []);
  byPackage.get(packageName).push({ specifier, bare });
}

let created = 0;
let updated = 0;
let skipped = 0;

for (const [packageName, entries] of byPackage) {
  const pkgDir = join(nodeModulesDir, packageName);
  const realPkgJson = join(pkgDir, "package.json");

  let exists = false;

  try {
    await access(realPkgJson);
    exists = true;
  } catch {
    /* not present */
  }

  if (exists) {
    // If a real npm package already lives here, don't clobber it.

    const existing = JSON.parse(await readFile(realPkgJson, "utf8"));

    if (existing?._ncm_builtin_shim !== true) {
      skipped++;
      continue;
    }
  }

  await mkdir(pkgDir, { recursive: true });

  //
  // Write each entry's shim file. Sub-paths live under
  // node_modules/<name>/<sub-path>.js so require('fs/promises') can
  // find it without leaving the package root.
  //

  const exports = {
    "./package.json": "./package.json",
  };

  // Sort entries so the bare name (e.g. "fs") is written first — it
  // becomes the `main` and `exports['.']`.

  entries.sort((a, b) => {
    const aBare = a.specifier === packageName;
    const bBare = b.specifier === packageName;

    if (aBare && !bBare) return -1;
    if (!aBare && bBare) return 1;
    return a.specifier.localeCompare(b.specifier);
  });

  let mainEntry = null;

  for (const { specifier, bare } of entries) {
    const rel = specifier + ".js";
    const abs = join(pkgDir, rel);

    await mkdir(dirname(abs), { recursive: true });

    const shimSource = `// AUTO-GENERATED by scripts/install-builtin-polyfills.mjs.
// Do not edit by hand — re-run the script after bumping
// bare-node-runtime.

'use strict'

module.exports = require(${JSON.stringify(bare)})

// ESM consumers that do \`import x from '${specifier}'\` read .default.
// Mirror the CJS export there for safety.

module.exports.default = module.exports
`;

    await writeFile(abs, shimSource);

    exports[`./${specifier}`] = `./${rel}`;

    if (specifier === packageName) {
      exports["."] = `./${rel}`;
      mainEntry = rel;
    }
  }

  const pkgJson = {
    name: packageName,
    version: "0.0.0",
    private: true,
    description:
      `Auto-generated builtin shim for bare-pack. Re-exports the ` +
      entries.map((e) => e.bare).join(", ") +
      ".",
    main: mainEntry,
    _ncm_builtin_shim: true,
    exports,
  };

  await writeFile(realPkgJson, JSON.stringify(pkgJson, null, 2) + "\n");

  if (exists) updated++;
  else created++;
}

console.log(
  `[install-builtin-polyfills] created=${created} updated=${updated} skipped=${skipped}`,
);

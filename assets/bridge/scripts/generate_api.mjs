#!/usr/bin/env node
// generate_api.mjs
//
// Static regenerator for assets/bridge/generated_api.js.
//
// `main.js` from @neteasecloudmusicapienhanced/api loads its module/ folder
// dynamically (fs.readdirSync) and pulls `./server` via getter + Object.assign.
// That makes it impossible for esbuild to follow those imports when bundling
// from bridge.js.
//
// This script mirrors main.js's public surface WITHOUT server.js, writing a
// generated_api.js whose every require() is statically analyzable so esbuild
// can recursively bundle module/, util/, and their transitive deps.
//
// Run:  node scripts/generate_api.mjs
// Idempotent: safe to re-run, output is deterministic.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const bridgeDir = path.resolve(__dirname, '..');
const apiDir = path.resolve(
  bridgeDir,
  'node_modules/@neteasecloudmusicapienhanced/api',
);
const moduleDir = path.join(apiDir, 'module');
const outFile = path.join(bridgeDir, 'generated_api.js');

// ---------------------------------------------------------------------------
// 1. Discover module/*.js the same way main.js does (reversed lex order).
// ---------------------------------------------------------------------------

const moduleFiles = fs
  .readdirSync(moduleDir)
  .filter((f) => f.endsWith('.js'))
  .reverse();

// fn name = filename minus extension, exactly like main.js:
//   file.split('.').shift()
const fnEntries = moduleFiles.map((f) => {
  const fn = f.split('.').shift();
  return { file: f, fn };
});

// ---------------------------------------------------------------------------
// 2. Emit generated_api.js.
// ---------------------------------------------------------------------------

const lines = [];
const push = (s = '') => lines.push(s);

push(`// AUTO-GENERATED by scripts/generate_api.mjs — DO NOT EDIT.`);
push(`//`);
push(`// Source: node_modules/@neteasecloudmusicapienhanced/api/main.js`);
push(`//`);
push(`// This file mirrors main.js's public surface, minus server.js, with`);
push(`// statically analyzable requires so esbuild can recursively bundle`);
push(`// the full dependency graph (module/*.js, util/*.js, etc).`);
push(`//`);
push(`// Regenerate:  node scripts/generate_api.mjs`);
push(``);
push(`'use strict';`);
push(``);
push(`const { cookieToJson } = require('./node_modules/@neteasecloudmusicapienhanced/api/util');`);
push(``);
push(`// Lazy-loaded on first request, matches main.js behavior.`);
push(`let _request = null;`);
push(`function _loadRequest() {`);
push(`  if (!_request) {`);
push(`    _request = require('./node_modules/@neteasecloudmusicapienhanced/api/util/request');`);
push(`  }`);
push(`  return _request;`);
push(`}`);
push(``);
// Use a Map so iteration order is guaranteed to match insertion order
// (matching main.js's reversed lex order), and so we never collide with a
// filename that happens to be "__proto__" / "constructor" / etc.
push(`const _modules = new Map([`);

for (const { file, fn } of fnEntries) {
  push(
    `  [${JSON.stringify(fn)}, require('./node_modules/@neteasecloudmusicapienhanced/api/module/${file}')],`,
  );
}

push(`]);`);
push(``);
push(`// Build the per-fn dispatcher exactly like main.js: cookie normalization +`);
push(`// lazy request loader injected as the second argument.`);
push(`const _wrapped = {};`);
push(`for (const [fn, fileModule] of _modules) {`);
push(`  _wrapped[fn] = function (data = {}) {`);
push(`    const cookie =`);
push(`      typeof data.cookie === 'string'`);
push(`        ? cookieToJson(data.cookie)`);
push(`        : data.cookie || {};`);
push(`    return fileModule(`);
push(`      { ...data, cookie },`);
push(`      async (...args) => _loadRequest()(...args),`);
push(`    );`);
push(`  };`);
push(`}`);
push(``);
push(`module.exports = _wrapped;`);
push(``);
push(`// Expose request() so the bridge can pre-warm or call it directly if needed.`);
push(`module.exports.request = (...args) => _loadRequest()(...args);`);
push(``);

// ---------------------------------------------------------------------------
// 3. Write.
// ---------------------------------------------------------------------------

fs.writeFileSync(outFile, lines.join('\n') + '\n', 'utf8');

// ---------------------------------------------------------------------------
// 4. Summary (single line — friendly to cron).
// ---------------------------------------------------------------------------

const fnNames = fnEntries.map((e) => e.fn);
console.log(
  `[generate_api] wrote ${path.relative(bridgeDir, outFile)} ` +
    `(${fnNames.length} fns, excludes server.js)`,
);
